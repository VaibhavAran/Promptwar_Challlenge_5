/**
 * AI-powered Checklist component.
 * Merges AI-generated tasks with user-added tasks and preserves completion state.
 * Supports task completion toggling, custom task addition, filtering, and export.
 */

import React, { useState, useEffect } from 'react';
import {
  CheckSquare,
  Square,
  Plus,
  Trash2,
  Download,
  RefreshCw,
  Loader2,
  Sparkles,
} from 'lucide-react';
import type { EventDraft } from '../../types/event';
import type {
  GeneratedEventPlan,
  ChecklistEntry,
  RegenerableSection,
} from '../../types/generatedPlan';
import { Card } from '../common/Card';
import { Button } from '../common/Button';
import { Badge } from '../common/Badge';

type UserTask = ChecklistEntry & { userAdded?: boolean };

function checklistStorageKey(eventDraftId: string): string {
  return `gatherly_checklist_${eventDraftId}`;
}

function loadSavedTasks(eventDraftId: string): UserTask[] {
  try {
    const raw = localStorage.getItem(checklistStorageKey(eventDraftId));
    if (!raw) return [];
    const parsed = JSON.parse(raw) as UserTask[];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function copyChecklistText(text: string): Promise<void> {
  if (navigator.clipboard?.writeText) {
    return navigator.clipboard.writeText(text);
  }

  const textarea = document.createElement('textarea');
  textarea.value = text;
  textarea.setAttribute('readonly', '');
  textarea.style.position = 'fixed';
  textarea.style.opacity = '0';
  document.body.appendChild(textarea);
  textarea.select();
  const copied = document.execCommand('copy');
  textarea.remove();
  return copied ? Promise.resolve() : Promise.reject(new Error('Clipboard unavailable'));
}

interface AiChecklistProps {
  draft: EventDraft;
  plan: GeneratedEventPlan | null;
  isGenerating: boolean;
  onRegenerate: (section: RegenerableSection) => void;
  onGenerate?: () => void;
}

export const AiChecklist: React.FC<AiChecklistProps> = ({
  draft,
  plan,
  isGenerating,
  onRegenerate,
  onGenerate,
}) => {
  const [tasks, setTasks] = useState<UserTask[]>(() => loadSavedTasks(draft.id));
  const [filter, setFilter] = useState<string>('All');
  const [newText, setNewText] = useState('');
  const [newCategory, setNewCategory] =
    useState<ChecklistEntry['category']>('Logistics');
  const [copiedNotice, setCopiedNotice] = useState(false);

  // Sync AI-generated tasks when plan changes
  // Preserve user-added tasks and completion states across regenerations
  useEffect(() => {
    if (!plan?.checklist) return;

    setTasks((prev) => {
      const userTasks = prev.filter((t) => t.userAdded);
      const completionMap = new Map(prev.map((t) => [t.id, t.completed]));

      const aiTasks: UserTask[] = plan.checklist.map((t) => ({
        ...t,
        completed: completionMap.get(t.id) ?? false,
        userAdded: false,
      }));

      return [...aiTasks, ...userTasks];
    });
  }, [plan?.checklist]);

  // Keep user-added tasks and completion state when switching tabs or
  // reopening the workspace.
  useEffect(() => {
    try {
      localStorage.setItem(checklistStorageKey(draft.id), JSON.stringify(tasks));
    } catch {
      /* ignore storage quota limits */
    }
  }, [draft.id, tasks]);

  const toggleTask = (id: string) =>
    setTasks((prev) =>
      prev.map((t) => (t.id === id ? { ...t, completed: !t.completed } : t)),
    );

  const deleteTask = (id: string) =>
    setTasks((prev) => prev.filter((t) => t.id !== id));

  const handleAddTask = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newText.trim()) return;
    const newTask: UserTask = {
      id: `user-task-${Date.now()}`,
      category: newCategory,
      text: newText.trim(),
      priority: 'medium',
      timing: 'User-added task',
      completed: false,
      userAdded: true,
    };
    setTasks((prev) => [newTask, ...prev]);
    setNewText('');
  };

  const handleExport = () => {
    const lines = [
      `GATHERLY AI — CELEBRATION READINESS CHECKLIST`,
      `Celebration: ${draft.eventName || 'Untitled Event'}`,
      `Date: ${draft.date || 'TBD'} | Location: ${draft.city || 'TBD'}`,
      `Guests: ${draft.guestCount || '—'} | Budget: ${draft.currency} ${draft.budget || '—'}`,
      '',
      `TASKS PROGRESS: ${tasks.filter((t) => t.completed).length}/${tasks.length} Complete (${tasks.length > 0 ? Math.round((tasks.filter((t) => t.completed).length / tasks.length) * 100) : 0}%):`,
      ...tasks.map(
        (t) =>
          `[${t.completed ? 'X' : ' '}] [${t.category}] [${t.priority.toUpperCase()}] ${t.text}${t.timing ? ` — (${t.timing})` : ''}`,
      ),
      '',
      'Generated by Gatherly AI (Gemini Engine)',
    ].join('\n');

    void copyChecklistText(lines).then(
      () => {
        setCopiedNotice(true);
        setTimeout(() => setCopiedNotice(false), 3000);
      },
      () => setCopiedNotice(false),
    );
  };

  const filteredTasks = tasks.filter((t) => {
    if (filter === 'All') return true;
    if (filter === 'Completed') return t.completed;
    if (filter === 'Pending') return !t.completed;
    if (filter === 'My Tasks') return !!t.userAdded;
    return t.category === filter;
  });

  const completedCount = tasks.filter((t) => t.completed).length;
  const isAiGenerated = !!plan?.checklist?.length;

  const priorityColors: Record<string, string> = {
    high: 'bg-red-50 border-red-200 text-red-700',
    medium: 'bg-amber-50 border-amber-200 text-amber-700',
    low: 'bg-emerald-50 border-emerald-200 text-emerald-700',
  };

  return (
    <div className="space-y-6">
      <Card className="p-6 border-sand-200">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-5 border-b border-sand-200 gap-4">
          <div>
            <div className="flex items-center gap-2 mb-1">
              <Badge variant={isAiGenerated ? 'coral' : 'sand'}>
                {isAiGenerated ? 'AI-Generated Checklist' : 'Task Board'}
              </Badge>
              <span className="text-xs text-charcoal-500 font-mono">
                {completedCount}/{tasks.length} complete (
                {tasks.length > 0
                  ? Math.round((completedCount / tasks.length) * 100)
                  : 0}
                %)
              </span>
            </div>
            <h3 className="font-serif text-xl font-bold text-charcoal-900">
              Celebration Readiness Board
            </h3>
          </div>

          <div className="flex items-center gap-2 flex-wrap">
            {isAiGenerated && (
              <Button
                variant="secondary"
                size="sm"
                onClick={() => onRegenerate('checklist')}
                disabled={isGenerating}
                leftIcon={
                  isGenerating ? (
                    <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  ) : (
                    <RefreshCw className="w-3.5 h-3.5" />
                  )
                }
              >
                {isGenerating ? 'Regenerating…' : 'Regenerate Checklist'}
              </Button>
            )}
            <Button
              variant="secondary"
              size="sm"
              onClick={handleExport}
              leftIcon={<Download className="w-3.5 h-3.5 text-coral-600" />}
            >
              {copiedNotice ? 'Copied to Clipboard!' : 'Export Tasks'}
            </Button>
          </div>
        </div>

        {/* Progress Bar */}
        <div className="w-full h-2 rounded-full bg-sand-200 mt-4 overflow-hidden">
          <div
            className="h-full bg-coral-500 transition-all duration-500"
            style={{
              width: `${tasks.length > 0 ? (completedCount / tasks.length) * 100 : 0}%`,
            }}
          />
        </div>

        {/* Awaiting generation callout if empty */}
        {!isAiGenerated && tasks.length === 0 && (
          <div className="py-10 text-center max-w-md mx-auto">
            <Sparkles className="w-8 h-8 text-coral-300 mx-auto mb-2" />
            <h4 className="font-serif text-base font-bold text-charcoal-800 mb-1">
              No AI tasks generated yet
            </h4>
            <p className="text-xs text-charcoal-600 leading-relaxed mb-4">
              Generate your plan to receive 8-10 categorized, time-sensitive milestones across vendors, logistics, decor, and guest management.
            </p>
            {onGenerate && (
              <Button
                variant="primary"
                size="sm"
                onClick={onGenerate}
                disabled={isGenerating}
                leftIcon={isGenerating ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Sparkles className="w-3.5 h-3.5" />}
                className="mb-2"
              >
                {isGenerating ? 'Generating…' : 'Generate AI Checklist'}
              </Button>
            )}
            <p className="text-[11px] text-charcoal-400">
              You can also add custom tasks manually below anytime.
            </p>
          </div>
        )}

        {/* Add Task Input Form */}
        <form onSubmit={handleAddTask} className="mt-6 flex flex-col sm:flex-row gap-2">
          <input
            type="text"
            placeholder="Add custom task or errand (e.g., Confirm table linens with florist)..."
            value={newText}
            onChange={(e) => setNewText(e.target.value)}
            className="flex-1 px-3.5 py-2 text-sm rounded-lg bg-ivory-50 text-charcoal-900 border border-sand-300 focus:bg-white focus:outline-none focus:ring-2 focus:ring-coral-500/20 focus:border-coral-500"
          />
          <select
            value={newCategory}
            onChange={(e) =>
              setNewCategory(e.target.value as ChecklistEntry['category'])
            }
            className="px-3 py-2 text-xs font-semibold rounded-lg bg-ivory-50 border border-sand-300 text-charcoal-700 cursor-pointer"
          >
            <option value="Vendor">Vendor</option>
            <option value="Logistics">Logistics</option>
            <option value="Guests">Guests</option>
            <option value="Decor">Decor</option>
            <option value="Safety">Safety</option>
          </select>
          <Button
            type="submit"
            variant="primary"
            size="sm"
            leftIcon={<Plus className="w-3.5 h-3.5" />}
          >
            Add Task
          </Button>
        </form>

        {/* Filter Pills */}
        <div className="flex flex-wrap gap-1.5 mt-5 pt-4 border-t border-sand-200">
          {[
            'All',
            'Pending',
            'Completed',
            'My Tasks',
            'Vendor',
            'Logistics',
            'Guests',
            'Decor',
            'Safety',
          ].map((cat) => (
            <button
              key={cat}
              onClick={() => setFilter(cat)}
              className={`px-2.5 py-1 rounded-md text-xs font-medium transition-all ${
                filter === cat
                  ? 'bg-charcoal-900 text-white shadow-subtle'
                  : 'bg-sand-100 text-charcoal-600 hover:text-charcoal-900 hover:bg-sand-200'
              }`}
            >
              {cat}
            </button>
          ))}
        </div>

        {/* Task Rows */}
        <div className="mt-4 divide-y divide-sand-200">
          {filteredTasks.length === 0 ? (
            <p className="py-6 text-center text-xs text-charcoal-400">
              No tasks match the selected filter.
            </p>
          ) : (
            filteredTasks.map((t) => (
              <div
                key={t.id}
                className="py-3 flex items-center justify-between gap-3 group hover:bg-sand-50/50 px-2 rounded-lg transition-colors"
              >
                <div className="flex items-center gap-3 flex-1 min-w-0">
                  <button
                    onClick={() => toggleTask(t.id)}
                    className="text-coral-500 hover:text-coral-600 transition-colors shrink-0"
                    aria-label={t.completed ? 'Mark incomplete' : 'Mark complete'}
                  >
                    {t.completed ? (
                      <CheckSquare className="w-5 h-5 text-coral-600" />
                    ) : (
                      <Square className="w-5 h-5 text-sand-400 group-hover:text-charcoal-500" />
                    )}
                  </button>

                  <div className="flex-1 min-w-0">
                    <span
                      className={`text-xs sm:text-sm font-medium ${
                        t.completed
                          ? 'line-through text-charcoal-400'
                          : 'text-charcoal-800'
                      }`}
                    >
                      {t.text}
                    </span>
                    {t.timing && (
                      <p className="text-[11px] text-charcoal-400 mt-0.5">
                        {t.timing}
                      </p>
                    )}
                  </div>

                  <div className="flex items-center gap-1.5 shrink-0">
                    <span
                      className={`text-[10px] font-semibold px-1.5 py-0.5 rounded border ${
                        priorityColors[t.priority] ?? ''
                      } hidden sm:inline-block`}
                    >
                      {t.priority}
                    </span>
                    <span className="text-[10px] font-semibold uppercase tracking-wider px-1.5 py-0.5 rounded bg-sand-200 text-charcoal-600 hidden sm:inline-block">
                      {t.category}
                    </span>
                    {t.userAdded && (
                      <span className="text-[10px] font-semibold px-1.5 py-0.5 rounded bg-charcoal-100 text-charcoal-500 hidden sm:inline-block">
                        User-added
                      </span>
                    )}
                  </div>
                </div>

                <button
                  onClick={() => deleteTask(t.id)}
                  className="opacity-0 group-hover:opacity-100 text-charcoal-400 hover:text-red-500 p-1 transition-opacity"
                  aria-label="Delete task"
                >
                  <Trash2 className="w-4 h-4" />
                </button>
              </div>
            ))
          )}
        </div>
      </Card>
    </div>
  );
};
